/** Looks up a dotted key such as "help.basics.summary". */
export function textAt(key) {
  let value = TEXT;
  for (const part of key.split(".")) {
    if (value === undefined || value === null) break;
    value = value[part];
  }
  if (value === undefined) throw Error("Unknown text key: " + key);
  return value;
}
